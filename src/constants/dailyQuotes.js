/**
 * Get a random quote from the collection
 * @returns {Object} A random quote object
 */
export const getRandomQuote = () => {
  const randomIndex = Math.floor(Math.random() * dailyQuotes.length);
  return dailyQuotes[randomIndex];
};

/**
 * Get quotes filtered by mood/category
 * @param {string|Array} moodFilter - Mood(s) to filter by
 * @param {string} categoryFilter - Category to filter by (optional)
 * @returns {Array} Filtered quotes array
 */
export const getQuotesByMood = (moodFilter, categoryFilter = null) => {
  let filtered = dailyQuotes;

  // Filter by category if provided
  if (categoryFilter) {
    filtered = filtered.filter((quote) => quote.category === categoryFilter);
  }

  // Filter by mood
  if (moodFilter) {
    const moods = Array.isArray(moodFilter) ? moodFilter : [moodFilter];
    filtered = filtered.filter((quote) =>
      moods.some((mood) => quote.mood.includes(mood))
    );
  }

  return filtered;
};

/**
 * Get a random quote filtered by mood/category
 * @param {string|Array} moodFilter - Mood(s) to filter by
 * @param {string} categoryFilter - Category to filter by (optional)
 * @returns {Object} A random quote object matching the filters
 */
export const getRandomQuoteByMood = (moodFilter, categoryFilter = null) => {
  const filtered = getQuotesByMood(moodFilter, categoryFilter);
  if (filtered.length === 0) {
    return getRandomQuote(); // Fallback to any random quote
  }
  const randomIndex = Math.floor(Math.random() * filtered.length);
  return filtered[randomIndex];
};

/**
 * Get quote by ID
 * @param {number} id - Quote ID
 * @returns {Object|null} Quote object or null if not found
 */
export const getQuoteById = (id) => {
  return dailyQuotes.find((quote) => quote.id === id) || null;
};

